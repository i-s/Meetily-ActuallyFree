import React from 'react';
import { act, create, type ReactTestRenderer } from 'react-test-renderer';
import { expect, mock, test } from 'bun:test';
const events = new Map<string, any>();
Object.assign(globalThis, { window: { setTimeout, clearTimeout, addEventListener: (name: string, fn: any) => events.set(name, fn), removeEventListener: (name: string) => events.delete(name) } });
const calls: string[] = [];
let route = '';
let resolveSlow!: (value: any) => void;
mock.module('@tauri-apps/api/core', () => ({ invoke: async (command: string, args: any) => {
  calls.push(command);
  if (command !== 'api_global_search') throw new Error(command);
  if (args.query === 'slow') return new Promise(resolve => { resolveSlow = resolve; });
  return [{ kind: 'notes', id: 'notes-m', meetingId: 'm', title: 'Past meeting', snippet: 'Моя МыСлЬ' }, { kind: 'transcript', id: 'line', transcriptId: 'line', meetingId: 't', title: 'Said', snippet: 'Сказанное', audioStartTime: 12.75 }];
} }));
mock.module('next/navigation', () => ({ useRouter: () => ({ push: (href: string) => { route = href; } }), usePathname: () => '/' }));
mock.module('@/contexts/RecordingStateContext', () => ({ useRecordingState: () => ({ isRecording: true, isPaused: false }) }));
mock.module('@/contexts/ImportDialogContext', () => ({ useImportDialog: () => ({ openImportDialog() {} }) }));
mock.module('@/contexts/WorkspaceContext', () => ({ useWorkspace: () => ({ groups: [] }) }));
mock.module('@/components/Sidebar/SidebarProvider', () => ({ useSidebar: () => ({ meetings: [{ id: 'recent', title: 'Recent' }] }) }));
mock.module('@/lib/app-theme', () => ({ THEMES: [], useAppTheme: () => ['light', () => {}] }));
mock.module('@/components/groups/GroupEditor', () => ({ openGroupEditor() {} }));
mock.module('@/lib/recording-launch', () => ({ launchRecording() {}, requestRecordingStop() {} }));
const Wrap = ({ children }: any) => <div>{children}</div>;
mock.module('@/components/ui/avatar', () => ({ Avatar: Wrap }));
mock.module('@/components/ui/surface', () => ({ Kbd: Wrap }));
mock.module('@/components/ui/spinner', () => ({ Spinner: Wrap }));
mock.module('@/components/ui/command', () => ({ CommandDialog: ({ open, children }: any) => open ? <div>{children}</div> : null, CommandGroup: ({ heading, children }: any) => <section><h2>{heading}</h2>{children}</section>, CommandInput: ({ onValueChange, ...props }: any) => <input {...props} onChange={event => onValueChange(event.target.value)} />, CommandItem: ({ onSelect, children, ...props }: any) => <button {...props} onClick={onSelect}>{children}</button>, CommandList: Wrap, CommandShortcut: Wrap }));
const { default: GlobalSearchDialog } = await import('../../src/components/GlobalSearchDialog');
const rendered = (node: any): string => typeof node === 'string' ? node : Array.isArray(node) ? node.map(rendered).join(' ') : (node?.children ?? []).map(rendered).join(' ');
const pause = () => new Promise(resolve => setTimeout(resolve, 250));
const query = (root: ReactTestRenderer, value: string) => root.root.findByType('input').props.onChange({ target: { value } });

test('normal global search opens Notes and exact transcript moment without changing live Q&A context', async () => {
  let root!: ReactTestRenderer;
  await act(async () => { root = create(<GlobalSearchDialog />); });
  await act(async () => events.get('open-global-search')());
  await act(async () => root.root.findByProps({ value: 'recent-recent' }).props.onSelect());
  await act(async () => { await new Promise(resolve => setTimeout(resolve, 1)); });
  expect(route).toBe('/meeting-details?id=recent');
  await act(async () => events.get('open-global-search')());
  await act(async () => query(root, 'мысль'));
  await act(async () => { await pause(); });
  expect(rendered(root.toJSON())).toContain('Your Notes — not recognized speech');
  await act(async () => root.root.findByProps({ value: 'notes-notes-m' }).props.onSelect());
  await act(async () => { await new Promise(resolve => setTimeout(resolve, 1)); });
  expect(route).toBe('/meeting-details?id=m&section=notes');
  expect([...new Set(calls)]).toEqual(['api_global_search']);
  await act(async () => events.get('open-global-search')());
  await act(async () => query(root, 'slow'));
  await act(async () => { await pause(); });
  await act(async () => query(root, 'current'));
  expect(rendered(root.toJSON())).not.toContain('Моя МыСлЬ');
  await act(async () => { await pause(); resolveSlow([{ kind: 'notes', id: 'stale', meetingId: 'bad', snippet: 'STALE' }]); });
  expect(rendered(root.toJSON())).not.toContain('STALE');
  await act(async () => root.root.findByProps({ value: 'transcript-line' }).props.onSelect());
  await act(async () => { await new Promise(resolve => setTimeout(resolve, 1)); });
  expect(route).toBe('/meeting-details?id=t&t=line&ts=12.75');
  await act(async () => root.unmount());
});
